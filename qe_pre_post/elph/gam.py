import numpy as np
f=open('gam.lines','r')
lines=f.readlines()
f.close

np.set_printoptions(suppress=True)
np.set_printoptions(precision=4)

for line in lines[3:]:
    values=[x for x in line[:].split()]
    if values[0]=='Broadening':
       a=values[1]
       tmp1=np.zeros((1,9)) #tmp1 was used to save gammalines for one broadening
       tmp2=[]
    if len(values)==1: 
        tmp2=[]  #tmp2 was used to save gammalines of one q point for modes
    if len(values)==9: 
        tmp2.append([float(x) for x in values[:]])
    if len(tmp2)==1:
        # tmp2[0].extend(tmp2[1])
        # tmp2[0].extend(tmp2[2])
        tmp2=np.array(tmp2)
        # tmp2=tmp2.reshape(1,24)
        tmp1=np.vstack((tmp1,tmp2))
    if len(tmp1)==300:
        tmp1=np.array(tmp1)
        dat=tmp1[1:]
        np.savetxt(a,dat,fmt='%.04f')

        
        
        
        
        
    